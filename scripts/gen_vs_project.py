#!/usr/bin/env python3
"""生成 / 刷新 Visual Studio 解决方案文件。

    python scripts/gen_vs_project.py

产出：
    ClassConnector.sln    —— 双击即可用 Visual Studio 打开
    ClassConnector.pyproj —— Python 项目（F5 调试绿色便携入口）

新增或删除源码文件后重新运行本脚本即可保持项目文件同步。
.sln 与 .pyproj 均以 CRLF + UTF-8(无 BOM) 写出，兼容 Visual Studio。
"""

from __future__ import annotations

import sys
from pathlib import Path
from xml.sax.saxutils import escape as xml_escape

ROOT = Path(__file__).resolve().parent.parent

# 与 scripts/package.py 保持一致的排除规则
EXCLUDE_DIRS = {
    "__pycache__", ".pytest_cache", ".git", ".classconnector", ".vscode",
    "data", "runtime", "dist", "build", "venv", ".venv", "env", "node_modules",
}
EXCLUDE_SUFFIXES = {".pyc", ".pyo", ".log", ".wav", ".mp3", ".zip", ".pid", ".egg-info"}
EXCLUDE_FILES = {"ClassConnector.pyproj", "ClassConnector.sln"}

PROJECT_GUID = "{2F7B1A6C-3D4E-4A1B-9C8D-7E6F5A4B3C2D}"
PYTHON_PROJECT_TYPE = "{888888A0-9F3D-457C-B088-3A5042F75D52}"
PTVS_FLAVOR = "{a41c8ea1-112a-4a2d-9f91-29557995525f}"
SOLUTION_FOLDER_TYPE = "{2150E333-8FDC-42A3-9474-1A3956D46DE8}"
SOLUTION_FOLDER_GUID = "{9C1A2B3D-4E5F-4A6B-8C7D-1E2F3A4B5C6D}"
SOLUTION_GUID = "{A0B1C2D3-E4F5-4A6B-8C7D-9E0F1A2B3C4D}"

SOLUTION_ITEMS = [
    "README.md",
    "PORTABLE.txt",
    "requirements.txt",
    "requirements-portable.txt",
    "requirements-dev.txt",
    "docs\\PORTABLE.md",
    "docs\\VISUAL_STUDIO.md",
    "docs\\ARCHITECTURE.md",
    "docs\\API.md",
    "docs\\FAQ.md",
]


def iter_files() -> list[Path]:
    files: list[Path] = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT)
        if any(part in EXCLUDE_DIRS for part in rel.parts[:-1]):
            continue
        if path.suffix.lower() in EXCLUDE_SUFFIXES:
            continue
        if path.name in EXCLUDE_FILES:
            continue
        files.append(rel)
    return files


def win(path: Path) -> str:
    return str(path).replace("/", "\\")


def attr(value: str) -> str:
    return xml_escape(value, {'"': "&quot;"})


def build_pyproj(files: list[Path]) -> str:
    compile_items: list[str] = []
    content_items: list[str] = []
    folders: set[str] = set()

    for rel in files:
        w = win(rel)
        parts = rel.parts[:-1]
        for i in range(1, len(parts) + 1):
            folders.add("\\".join(parts[:i]) + "\\")
        if rel.suffix.lower() == ".py":
            compile_items.append(f'    <Compile Include="{attr(w)}" />')
        else:
            content_items.append(f'    <Content Include="{attr(w)}" />')

    folder_items = "\n".join(
        f'    <Folder Include="{attr(f)}" />' for f in sorted(folders))

    return f"""<?xml version="1.0" encoding="utf-8"?>
<Project ToolsVersion="4.0" DefaultTargets="Build" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">
  <!-- Generated by scripts/gen_vs_project.py - edit that script, not this file. -->
  <PropertyGroup>
    <Configuration Condition=" '$(Configuration)' == '' ">Debug</Configuration>
    <SchemaVersion>2.0</SchemaVersion>
    <ProjectGuid>{PROJECT_GUID}</ProjectGuid>
    <ProjectHome>.</ProjectHome>
    <StartupFile>agent\\portable.py</StartupFile>
    <SearchPath>.</SearchPath>
    <WorkingDirectory>.</WorkingDirectory>
    <OutputPath>.</OutputPath>
    <Name>ClassConnector</Name>
    <RootNamespace>ClassConnector</RootNamespace>
    <ProjectTypeGuids>{PTVS_FLAVOR};{PYTHON_PROJECT_TYPE.lower()}</ProjectTypeGuids>
    <LaunchProvider>Standard Python launcher</LaunchProvider>
    <CommandLineArguments>--no-browser</CommandLineArguments>
    <TestFramework>Pytest</TestFramework>
    <IsWindowsApplication>False</IsWindowsApplication>
  </PropertyGroup>
  <PropertyGroup Condition=" '$(Configuration)' == 'Debug' ">
    <DebugSymbols>true</DebugSymbols>
    <EnableUnmanagedDebugging>false</EnableUnmanagedDebugging>
  </PropertyGroup>
  <PropertyGroup Condition=" '$(Configuration)' == 'Release' ">
    <DebugSymbols>true</DebugSymbols>
    <EnableUnmanagedDebugging>false</EnableUnmanagedDebugging>
  </PropertyGroup>
  <ItemGroup>
{chr(10).join(compile_items)}
  </ItemGroup>
  <ItemGroup>
{chr(10).join(content_items)}
  </ItemGroup>
  <ItemGroup>
{folder_items}
  </ItemGroup>
  <!-- Python Tools targets are optional: VS can still open the project without the workload. -->
  <Import Project="$(MSBuildExtensionsPath32)\\Microsoft\\VisualStudio\\v$(VisualStudioVersion)\\Python Tools\\Microsoft.PythonTools.targets" Condition="Exists('$(MSBuildExtensionsPath32)\\Microsoft\\VisualStudio\\v$(VisualStudioVersion)\\Python Tools\\Microsoft.PythonTools.targets')" />
</Project>
"""


def build_sln() -> str:
    items = "\n".join(f"\t\t{i} = {i}" for i in SOLUTION_ITEMS)
    return f"""Microsoft Visual Studio Solution File, Format Version 12.00
# Visual Studio Version 17
VisualStudioVersion = 17.0.31903.59
MinimumVisualStudioVersion = 10.0.40219.1
Project("{PYTHON_PROJECT_TYPE}") = "ClassConnector", "ClassConnector.pyproj", "{PROJECT_GUID}"
EndProject
Project("{SOLUTION_FOLDER_TYPE}") = "Solution Items", "Solution Items", "{SOLUTION_FOLDER_GUID}"
\tProjectSection(SolutionItems) = preProject
{items}
\tEndProjectSection
EndProject
Global
\tGlobalSection(SolutionConfigurationPlatforms) = preSolution
\t\tDebug|Any CPU = Debug|Any CPU
\t\tRelease|Any CPU = Release|Any CPU
\tEndGlobalSection
\tGlobalSection(ProjectConfigurationPlatforms) = postSolution
\t\t{PROJECT_GUID}.Debug|Any CPU.ActiveCfg = Debug|Any CPU
\t\t{PROJECT_GUID}.Release|Any CPU.ActiveCfg = Release|Any CPU
\tEndGlobalSection
\tGlobalSection(SolutionProperties) = preSolution
\t\tHideSolutionNode = FALSE
\tEndGlobalSection
\tGlobalSection(ExtensibilityGlobals) = postSolution
\t\tSolutionGuid = {SOLUTION_GUID}
\tEndGlobalSection
EndGlobal
"""


def write_crlf(path: Path, text: str) -> None:
    normalized = text.replace("\r\n", "\n").replace("\n", "\r\n")
    path.write_bytes(normalized.encode("utf-8"))


def main() -> int:
    files = iter_files()
    sln = ROOT / "ClassConnector.sln"
    pyproj = ROOT / "ClassConnector.pyproj"
    write_crlf(sln, build_sln())
    write_crlf(pyproj, build_pyproj(files))
    print(f"生成完毕: {sln.name} + {pyproj.name}")
    print(f"  Compile: {sum(1 for f in files if f.suffix.lower() == '.py')} 个 Python 文件")
    print(f"  Content: {sum(1 for f in files if f.suffix.lower() != '.py')} 个其它文件")
    print("用 Visual Studio 双击 ClassConnector.sln 打开（需 Python 开发工作负载）。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
